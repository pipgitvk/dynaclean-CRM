CREATE TABLE IF NOT EXISTS registered_spares (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  warranty_product_id INT UNSIGNED NULL,
  dispatch_id INT UNSIGNED NULL,
  order_id VARCHAR(64) NULL,
  quote_number VARCHAR(128) NULL,
  spare_item_code VARCHAR(128) NULL,
  spare_item_name VARCHAR(255) NULL,
  serial_number VARCHAR(128) NULL,
  product_name VARCHAR(255) NULL,
  model VARCHAR(128) NULL,
  customer_name VARCHAR(255) NULL,
  contact_person VARCHAR(255) NULL,
  contact VARCHAR(64) NULL,
  email VARCHAR(255) NULL,
  customer_address TEXT NULL,
  state VARCHAR(128) NULL,
  installed_by VARCHAR(64) NULL,
  spare_installation_status VARCHAR(32) NULL,
  installation_completed_by VARCHAR(120) NULL,
  installation_completed_date DATE NULL,
  invoice_number VARCHAR(128) NULL,
  invoice_date DATE NULL,
  created_by VARCHAR(128) NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_registered_spares_order (order_id),
  KEY idx_registered_spares_serial (serial_number),
  KEY idx_registered_spares_dispatch (dispatch_id),
  KEY idx_registered_spares_wp (warranty_product_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;